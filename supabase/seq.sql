-- seq.sql — 그날 안의 차례를 **seq 하나로** 정한다. 2026-09-17에 만들었다.
-- ──────────────────────────────────────────────────────────────────────────
-- 지금까지 차례는 (on_date, at_time nulls last, seq) 였다. 시각이 먼저 이기므로
-- seq 는 **시각이 없는 줄들 사이에서만** 뜻이 있었고, 그래서 끌어서 옮길 수가 없었다 —
-- 시각이 적힌 줄은 seq 를 아무리 바꿔도 제자리로 돌아간다. 오사카 일정은 예순여섯 줄이
-- 전부 시각을 달고 있어서, 거기서는 '순서 바꾸기' 라는 말 자체가 성립하지 않았다.
--
-- 이제 차례는 **(on_date, seq)** 다. 시각은 적히는 값이지 줄 세우는 값이 아니다.
--   · 새 줄은 시각을 보고 제자리에 끼운다        (js/util.js 의 seqAt)
--   · 시각을 고치면 그 시각 자리로 다시 간다      (js/plan.js 의 valueOf)
--   · 끌어 옮기면 **그 자리에 남는다** — 시각과 어긋나도 사람이 그렇게 정한 것이다
--
-- ★★이 파일은 **지금 보이는 차례 그대로** seq 를 다시 매긴다. 안 돌리면 규칙이 바뀌는
--   순간 예전 줄들이 만든 차례(= 적어 넣은 순서)대로 뒤섞인다 — 화면이 통째로 흔들린다.
--   그러므로 **코드를 올리기 전에 이것부터 돌린다.**
-- ★열 칸씩 띄운다. 끌어 옮길 때 이웃 사이의 **가운데 수**를 쓰면 한 줄만 고치면 되는데,
--   1·2·3 으로 붙여 두면 사이가 없어 그날 전체를 다시 매겨야 한다.
-- ★결제 줄(parent_id)도 함께 매긴다. 화면에서는 부모 밑에 붙으므로 이 수를 안 보지만,
--   같은 날에 사는 줄이라 빼 두면 seq 가 군데군데 비어 뒷사람이 헷갈린다.
--
-- 멱등하다. 여러 번 실행해도 안전하다 — 한 번 매기고 나면 같은 차례라 같은 값이 나온다.

with n as (
  select id,
         row_number() over (
           partition by trip_id, on_date
           order by at_time nulls last, seq, created_at
         ) * 10 as s
  from trip.items
)
update trip.items i
   set seq = n.s
  from n
 where n.id = i.id
   and i.seq is distinct from n.s;

